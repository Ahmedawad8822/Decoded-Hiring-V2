// Detached process groups include Wrangler's proxy + user workerd and build subprocesses.
// Register immediately after spawn, before readiness/PID detection can fail.
const children = new Set<ChildProcess>();
const closers = new Set<() => void>();
function killGroup(proc: ChildProcess, signal: NodeJS.Signals) {
  if (!proc.pid) return;
  try { process.kill(-proc.pid, signal); } catch { /* group already gone */ }
}
async function stopChild(proc: ChildProcess) {
  killGroup(proc, "SIGTERM");
  const until = Date.now() + 3000;
  while (proc.exitCode === null && proc.signalCode === null && Date.now() < until) await sleep(50);
  killGroup(proc, "SIGKILL"); // also reap grandchildren if the parent already exited
  children.delete(proc);
}
async function cleanup() {
  for (const close of closers) close();
  await Promise.all([...children].map(stopChild));
}
for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.once(signal, () => { void cleanup().finally(() => process.exit(signal === "SIGINT" ? 130 : 143)); });
}
process.once("exit", () => { for (const proc of children) killGroup(proc, "SIGKILL"); });
async function sh(cmd: string, args: string[], env: Record<string, string> = {}, cwd = ROOT) {
  log(`$ ${cmd} ${args.join(" ")}`);
  const proc = spawn(cmd, args, { cwd, env: { ...process.env, WRANGLER_SEND_METRICS: "false", NEXT_TELEMETRY_DISABLED: "1", ...env }, stdio: "inherit", detached: true });
  children.add(proc);
  try {
    await new Promise<void>((resolve, reject) => {
      proc.once("error", reject);
      proc.once("exit", (code, signal) => code === 0 ? resolve() : reject(new Error(`${cmd} failed (exit ${code}, signal ${signal})`)));
    });
  } finally { await stopChild(proc); }
}
function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const srv = net.createServer();
    srv.listen(0, "127.0.0.1", () => {
      const { port } = srv.address() as net.AddressInfo;
      srv.close(() => resolve(port));
    });
    srv.on("error", reject);
  });
}

// ----------------------------------------------------------------------------
// CPU meter: ns-resolution user+system CPU of a pid
// ----------------------------------------------------------------------------
const PY_RUSAGE = `
import ctypes, ctypes.util, sys
libproc = ctypes.CDLL(ctypes.util.find_library("proc"))
libsys = ctypes.CDLL(ctypes.util.find_library("System"))
class TB(ctypes.Structure):
    _fields_ = [("numer", ctypes.c_uint32), ("denom", ctypes.c_uint32)]
tb = TB()
libsys.mach_timebase_info(ctypes.byref(tb))
class RU(ctypes.Structure):
    _fields_ = [("ri_uuid", ctypes.c_uint8 * 16), ("ri_user_time", ctypes.c_uint64), ("ri_system_time", ctypes.c_uint64), ("pad", ctypes.c_uint64 * 40)]
def cpu_ns(pid):
    buf = RU()
    if libproc.proc_pid_rusage(pid, 0, ctypes.byref(buf)) != 0:
        return -1
    return (buf.ri_user_time + buf.ri_system_time) * tb.numer // tb.denom
for line in sys.stdin:
    print(cpu_ns(int(line)), flush=True)
`;

class CpuMeter {
  private py: ChildProcess | null = null;
  private buf = "";
  private waiters: Array<{ resolve: (n: number) => void; reject: (err: Error) => void }> = [];
  private failure: Error | null = null;
  private ticks = 100;

  constructor() {
    if (process.platform === "darwin") {
      this.py = spawn("python3", ["-I", "-c", PY_RUSAGE], { detached: true, stdio: ["pipe", "pipe", "inherit"] });
      children.add(this.py);
      const fail = (err: Error) => {
        this.failure = err;
        for (const waiter of this.waiters.splice(0)) waiter.reject(err);
      };
      this.py.on("error", fail);
      this.py.on("exit", () => fail(new Error("CPU meter exited")));
      this.py.stdin!.on("error", fail);
      this.py.stdout!.on("data", (d: Buffer) => {
        this.buf += d.toString();
        let i: number;
        while ((i = this.buf.indexOf("\n")) >= 0) {
          const line = this.buf.slice(0, i);
          this.buf = this.buf.slice(i + 1);
          const waiter = this.waiters.shift();
          const n = Number(line);
          if (!Number.isFinite(n) || n < 0) waiter?.reject(new Error("Could not read workerd CPU counter"));
          else waiter?.resolve(n);
        }
      });
    } else if (process.platform === "linux") {
      this.ticks = Number(spawnSync("getconf", ["CLK_TCK"], { encoding: "utf8" }).stdout.trim());
      if (!(this.ticks > 0)) throw new Error("Cannot determine Linux CLK_TCK");
    } else {
      throw new Error(`Per-request CPU metering supports macOS and Linux only (got ${process.platform}).`);
    }
  }

  /** CPU nanoseconds (user + system) consumed so far by pid. */
  async read(pid: number): Promise<number> {
    if (this.py) {
      if (this.failure) throw this.failure;
      return new Promise((resolve, reject) => {
        const timer = setTimeout(() => reject(new Error("CPU meter read timed out")), 5000);
        this.waiters.push({ resolve: (n) => { clearTimeout(timer); resolve(n); }, reject: (err) => { clearTimeout(timer); reject(err); } });
        this.py!.stdin!.write(`${pid}\n`);
      });
    }
    // Linux: /proc/<pid>/stat utime+stime in clock ticks (read CLK_TCK above).
    const stat = fs.readFileSync(`/proc/${pid}/stat`, "utf8");
    const fields = stat.slice(stat.lastIndexOf(")") + 2).split(" ");
    return (Number(fields[11]) + Number(fields[12])) * (1e9 / this.ticks);
  }

  close() {
    this.py?.kill();
  }
}

