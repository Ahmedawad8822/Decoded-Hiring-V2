/** Module label from an esbuild "// path" banner path. */
function moduleLabel(banner: string | undefined): string {
  if (!banner) return "(unknown module)";
  let p = banner.replace(/^(\.\.\/)+/, "").replace(/^\.open-next\/(server-functions\/default\/)?/, "");
  const nm = p.lastIndexOf("node_modules/");
  if (nm >= 0) {
    const rest = p.slice(nm + "node_modules/".length).split("/");
    const pkg = rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
    const after = rest.slice(rest[0].startsWith("@") ? 2 : 1);
    if (pkg === "next" && after[0] === "dist" && after[1] === "compiled") return `next/dist/compiled/${after[2]}`;
    if (pkg === "next" && after[0] === "dist") return `next/dist/${after[1] ?? ""}`.replace(/\/$/, "");
    return pkg;
  }
  p = p.replace(/^\.next\/server\//, "app:");
  return p.split("/").slice(0, 4).join("/");
}

/**
 * warm mode: one instance, 3 warm-up requests, then 15 profiled requests per route.
 * cold mode: a FRESH instance per route and a single profiled request (module initialisation shows up).
 */
async function profileHot(
  startFresh: () => Promise<{ inst: Instance; inspectorPort: number }>,
  cold: boolean,
  routes: CpuRoute[],
  cookies: Record<string, string>,
  meter: CpuMeter,
): Promise<Hot[]> {
  let session: { inst: Instance; cdp: Cdp | null } | null = null;
  let cdp!: Cdp;
  let inst!: Instance;
  let sourceDirectory = "";
  let sessionNumber = 0;
  const sourceCache = new Map<string, { lines: number[]; names: string[]; src: string[] }>();
  const open = async () => {
    const fresh = await startFresh();
    inst = fresh.inst;
    session = { inst, cdp: null };
    cdp = await Cdp.connect(fresh.inspectorPort);
    session.cdp = cdp;
    await cdp.send("Debugger.enable");
    await cdp.send("Profiler.enable");
    await cdp.send("Profiler.setSamplingInterval", { interval: 100 });
    sourceDirectory = path.join(WORK, "sources", `${cold ? "cold" : "warm"}-${++sessionNumber}`);
    sourceCache.clear(); // script ids are per instance
    session = { inst, cdp };
  };
  const close = async () => {
    if (!session) return;
    session.cdp?.close();
    await session.inst.stop();
    session = null;
  };
  const bannerIndex = async (scriptId: string) => {
    let idx = sourceCache.get(scriptId);
    if (!idx) {
      const { scriptSource } = await cdp.send<{ scriptSource: string }>("Debugger.getScriptSource", { scriptId });
      const lines: number[] = [];
      const names: string[] = [];
      const src = scriptSource.split("\n");
      src.forEach((l, i) => {
        // esbuild banner ("// path") or a __commonJS/__esm wrapper key (wrangler re-bundles handler.mjs and drops the banners)
        const m = l.match(/^\/\/ (\S.*\.(?:[cm]?[jt]sx?|json|node))$/) ?? l.match(/^\s*"([^"]+\.(?:[cm]?[jt]sx?|json|node))"\(/);
        if (m) {
          lines.push(i);
          names.push(m[1]);
        }
      });
      fs.mkdirSync(sourceDirectory, { recursive: true });
      fs.writeFileSync(path.join(sourceDirectory, `script-${scriptId}.js`), scriptSource);
      idx = { lines, names, src };
      sourceCache.set(scriptId, idx);
    }
    return idx;
  };

  const out: Hot[] = [];
  try {
    for (const route of routes) {
      if (cold || !session) await close();
      if (!session) await open();
      if (!cold) for (let i = 0; i < 3; i++) await measureOnce(inst, meter, route, cookies); // warm up
      await cdp.send("Profiler.start");
      const reps = cold ? 1 : 15;
      for (let i = 0; i < reps; i++) await measureOnce(inst, meter, route, cookies, true);
      const { profile } = await cdp.send<{ profile: CdpProfile }>("Profiler.stop");
      const profileName = `${cold ? "cold" : "warm"}-${route.name.replace(/[^a-z0-9]+/gi, "-")}`;
      fs.writeFileSync(path.join(WORK, `${profileName}.cpuprofile`), JSON.stringify(profile));
      const byId = new Map(profile.nodes.map((n) => [n.id, n]));
      const self = new Map<string, number>();
      const mods = new Map<string, number>();
      let idle = 0;
      let busy = 0;
      for (let i = 0; i < profile.samples.length; i++) {
        // A sample after a blocked/sleeping stretch carries a huge delta (wall time in I/O wait),
        // so cap each sample at a few sampling intervals: self time ~ sample count x interval.
        const dt = Math.min(profile.timeDeltas[i], SAMPLE_CAP_US) / 1000;
        const node = byId.get(profile.samples[i]);
        if (!node) continue;
        const cf = node.callFrame;
        if (cf.functionName === "(idle)") {
          idle += dt;
          continue;
        }
        busy += dt;
        let mod = "(runtime / native)";
        let where = cf.url ? cf.url.split("/").pop() : "";
        let snippet = "";
        if (cf.scriptId && cf.scriptId !== "0" && cf.url && !cf.url.startsWith("node-internal:")) {
          const { lines, names, src } = await bannerIndex(cf.scriptId);
          snippet = (src[cf.lineNumber] ?? "").slice(cf.columnNumber, cf.columnNumber + 70).replace(/\s+/g, " ").replace(/[`|]/g, "'");
          // last banner at or before this function's line
          let lo = 0;
          let hi = lines.length - 1;
          let at = -1;
          while (lo <= hi) {
            const mid = (lo + hi) >> 1;
            if (lines[mid] <= cf.lineNumber) {
              at = mid;
              lo = mid + 1;
            } else hi = mid - 1;
          }
          mod = moduleLabel(at >= 0 ? names[at] : undefined);
          where = at >= 0 ? names[at].split("/").slice(-2).join("/") : where;
        } else if (cf.url.startsWith("node-internal:")) {
          mod = `workerd node-compat (${cf.url.replace("node-internal:", "")})`;
          where = cf.url.replace("node-internal:", "");
        } else if (cf.functionName.startsWith("(")) {
          mod = cf.functionName; // (program), (garbage collector)
        }
        const fn = cf.functionName || "(anonymous)";
        // minified / anonymous functions get a source excerpt so they can still be identified
        const hint = snippet && (fn.length <= 2 || fn === "(anonymous)") ? ` \`${snippet.slice(0, 60)}\`` : "";
        const key = `${fn} - ${mod === "(runtime / native)" ? where : mod}:${cf.lineNumber + 1}${hint}`;
        self.set(key, (self.get(key) ?? 0) + dt);
        mods.set(mod, (mods.get(mod) ?? 0) + dt);
      }
      const toRows = (m: Map<string, number>, n: number) =>
        [...m.entries()]
          .sort((a, b) => b[1] - a[1])
          .slice(0, n)
          .map(([label, selfMs]) => ({ label, selfMs: selfMs / reps, pct: (selfMs / busy) * 100 }));
      out.push({ sourceDirectory: path.relative(WORK, sourceDirectory), route: cold ? `${route.name} [cold: first request on a fresh instance]` : route.name, busyMs: busy / reps, idleMs: idle / reps, top: toRows(self, 12), byModule: toRows(mods, 8) });
      log(`hot-profile ${route.name}: ${(busy / reps).toFixed(1)} ms busy/request (profiler wall-based; ranking only)`);
    }
  } finally { await close(); }
  return out;
}

// ----------------------------------------------------------------------------
// Harness floor: an empty Worker under the same wrangler dev setup, so the
// per-request overhead of the harness itself is visible next to the results.
// ----------------------------------------------------------------------------
async function measureFloor(meter: CpuMeter, port: number): Promise<RouteResult> {
  const dir = path.join(WORK, "floor");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "index.mjs"),
    'export default { fetch() { return new Response("<html>ok</html>", { headers: { "content-type": "text/html" } }); } };\n',
  );
  const cfg = path.join(dir, "wrangler.json");
  fs.writeFileSync(
    cfg,
    JSON.stringify({
      name: "cpu-floor",
      main: path.join(dir, "index.mjs"),
      compatibility_date: "2026-09-15",
      compatibility_flags: ["nodejs_compat"],
    }),
  );
  const inst = await startInstance(cfg, port);
  try {
    const route: CpuRoute = { name: "(floor) empty Worker, same harness", path: "/", auth: "none" };
    const cold = await measureOnce(inst, meter, route, {});
    const warm: Sample[] = [];
    for (let i = 0; i < Math.max(RUNS, 30); i++) warm.push(await measureOnce(inst, meter, route, {}));
    return {
      route,
      status: statusLabel(cold, warm),
      cold,
      warm,
      warmCpu: summarize(warm.map((s) => s.cpuMs)),
      warmWall: summarize(warm.map((s) => s.wallMs)),
      cacheLabel: "-",
    };
  } finally {
    await inst.stop();
  }
}

// ----------------------------------------------------------------------------
// main
// ----------------------------------------------------------------------------
async function main() {
  if (process.env.CF_PAGES || process.env.CLOUDFLARE === "1") throw new Error("perf:cpu is local-only.");
  fs.mkdirSync(WORK, { recursive: true });
  const marker = path.join(WORK, ".dh-cpu-profiler");
  if (!fs.existsSync(marker) && fs.readdirSync(WORK).length) throw new Error("--work-dir must be empty or belong to an earlier profiler run");
  fs.writeFileSync(marker, "Throwaway CPU profiler artifacts\n");
  log(`work dir: ${WORK} (throwaway state in ${STATE_DIR})`);

  const seedEnv = {
    DH_LOCAL_STATE_DIR: STATE_DIR,
    BETTER_AUTH_SECRET: SECRET,
    ADMIN_INITIAL_EMAIL: PROFILE_ADMIN.email,
    ADMIN_INITIAL_PASSWORD: PROFILE_ADMIN.password,
    ADMIN_REQUIRE_2FA: "false",
    DH_AUTH_RATE_LIMIT_DISABLED: "1",
  };

  if (!SKIP_BUILD) {
    // 1. throwaway state: migrations + admin + demo course + offer + guides/field notes + learner
    fs.rmSync(STATE_ROOT, { recursive: true, force: true });
    await sh("npx", ["--no-install", "tsx", "scripts/profile-cpu-seed.ts"], seedEnv);

    // 2. production-shaped (minified) build, prerendered from the seeded DB
    await sh("npm", ["run", "cf:build"], { DH_LOCAL_STATE_DIR: STATE_DIR, BETTER_AUTH_SECRET: SECRET });
    fs.rmSync(OPEN_NEXT_MIN, { recursive: true, force: true });
    await sh("cp", ["-R", path.join(ROOT, ".open-next"), OPEN_NEXT_MIN]);

    // Populate only this run's R2, without ever writing the shared .wrangler directory.
    await sh("npx", ["--no-install", "tsx", "scripts/profile-cpu-seed.ts", "--cache", OPEN_NEXT_MIN], seedEnv);
    // Preserve pristine cache + DB for each cold route. Sign-in cookies are added below.

    // 4. unminified copy of the same build, ONLY used to give hot functions readable names
    if (HOT) {
      try {
        await sh("npx", ["--no-install", "opennextjs-cloudflare", "build", "--skipNextBuild", "--noMinify"], {
          DH_LOCAL_STATE_DIR: STATE_DIR,
          BETTER_AUTH_SECRET: SECRET,
        });
        fs.rmSync(OPEN_NEXT_DEV, { recursive: true, force: true });
        fs.cpSync(path.join(ROOT, ".open-next"), OPEN_NEXT_DEV, { recursive: true });
      } finally {
        fs.rmSync(path.join(ROOT, ".open-next"), { recursive: true, force: true });
        fs.cpSync(OPEN_NEXT_MIN, path.join(ROOT, ".open-next"), { recursive: true });
      }
    }
  }
  if (!fs.existsSync(OPEN_NEXT_MIN)) throw new Error(`No build found in ${OPEN_NEXT_MIN}; run without --skip-build first.`);

  const port = await freePort();
  const configMin = writeConfig("min", OPEN_NEXT_MIN, port);
  const meter = new CpuMeter();
  closers.add(() => meter.close());
  meterRef = meter;
  const results: RouteResult[] = [];
  const cookies: Record<string, string> = {};

  // 5. sign in once (cookies stay valid across restarts: same secret and D1 state)
  {
    const inst = await startInstance(configMin, port);
    try {
      for (const [role, creds] of [["admin", PROFILE_ADMIN], ["learner", PROFILE_LEARNER]] as const) {
        const res = await fetch(`http://127.0.0.1:${port}/api/auth/sign-in/email`, {
          method: "POST",
          headers: { "content-type": "application/json", origin: `http://127.0.0.1:${port}`, "x-forwarded-for": `10.9.${runSalt}.${role === "admin" ? 1 : 2}`, "cf-connecting-ip": `10.9.${runSalt}.${role === "admin" ? 1 : 2}` },
          body: JSON.stringify(creds),
          signal: AbortSignal.timeout(60_000),
        });
        const cookie = sessionCookie(res.headers.get("set-cookie"));
        if (!cookie) throw new Error(`${role} sign-in failed (HTTP ${res.status}): ${(await res.text()).slice(0, 200)}`);
        cookies[role] = cookie;
        await res.arrayBuffer();
      }
    } finally {
      await inst.stop();
    }
  }

  const snapshot = path.join(WORK, "state-snapshot");
  fs.rmSync(snapshot, { recursive: true, force: true });
  fs.cpSync(STATE_ROOT, snapshot, { recursive: true });
  const resetState = () => {
    fs.rmSync(STATE_ROOT, { recursive: true, force: true });
    fs.cpSync(snapshot, STATE_ROOT, { recursive: true });
  };
  const allRoutes = [...buildRoutes(), signInRoute(PROFILE_ADMIN)];
  const routes = ROUTE_FILTER
    ? allRoutes.filter((r) => ROUTE_FILTER.some((f) => r.path === f || r.name === f))
    : allRoutes;
  if (routes.length === 0) throw new Error("No routes matched --routes.");

  // 6. measure
  let warmInst: Instance | null = null;
  try {
    if (!COLD && !HOT_ONLY) warmInst = await startInstance(configMin, port);
    for (const route of HOT_ONLY ? [] : routes) {
      if (COLD) resetState();
      const inst = COLD ? await startInstance(configMin, port) : warmInst!;
      try {
        const cold = COLD ? await measureOnce(inst, meter, route, cookies) : undefined;
        if (!COLD) await measureOnce(inst, meter, route, cookies); // discarded warm-up
        const warm: Sample[] = [];
        for (let i = 0; i < RUNS; i++) warm.push(await measureOnce(inst, meter, route, cookies));
        const result: RouteResult = {
          route,
          status: statusLabel(cold, warm),
          cold,
          warm,
          warmCpu: summarize(warm.map((s) => s.cpuMs)),
          warmWall: summarize(warm.map((s) => s.wallMs)),
          cacheLabel: cacheLabel(cold, warm),
        };
        results.push(result);
        log(
          `${route.name.padEnd(38)} HTTP ${result.status}  cold ${fmt(cold?.cpuMs)} ms  warm p50 ${fmt(result.warmCpu.p50)} p95 ${fmt(result.warmCpu.p95)} max ${fmt(result.warmCpu.max)}`,
        );
      } finally {
        if (COLD) await inst.stop();
      }
    }
  } finally {
    if (warmInst) await warmInst.stop();
  }

  if (!ROUTE_FILTER && !HOT_ONLY) results.push(await measureFloor(meter, port));

  // 7. hot functions for the worst routes (unminified build, inspector attached)
  let hot: Hot[] = [];
  if (HOT && fs.existsSync(OPEN_NEXT_DEV)) {
    const worst = HOT_ROUTES
      ? allRoutes.filter((r) => HOT_ROUTES.some((f) => f === r.path || f === r.name))
      : [...results]
          .filter((r) => r.status === "200" && !r.route.name.startsWith("(floor)"))
          .sort((a, b) => b.warmCpu.p50 - a.warmCpu.p50)
          .slice(0, HOT_TOP)
          .map((r) => r.route);
    // Always include the worst learner and admin route even if neither makes the overall top N.
    if (!HOT_ROUTES) for (const role of ["learner", "admin"] as const) {
      const result = results.filter((r) => r.route.auth === role).sort((a, b) => b.warmCpu.p50 - a.warmCpu.p50)[0];
      if (result && !worst.some((r) => r.path === result.route.path)) worst.push(result.route);
    }
    const devConfig = writeConfig("dev", OPEN_NEXT_DEV, port);
    const startFresh = async () => {
      resetState();
      const inspectorPort = await freePort();
      return { inst: await startInstance(devConfig, port, inspectorPort), inspectorPort };
    };
    hot = await profileHot(startFresh, false, worst, cookies, meter);
    // First request on a fresh isolate: shows what module/route initialisation costs.
    const coldNames = (opt("cold-hot-routes") ?? "/about,/learn/courses/[slug] (learner)").split(",").map((s) => s.trim());
    const coldRoutes = allRoutes.filter((r) => coldNames.some((f) => f === r.path || f === r.name));
    if (!flag("no-cold-hot")) hot.push(...(await profileHot(startFresh, true, coldRoutes, cookies, meter)));
  }
  meter.close();

  // 8. report
  fs.writeFileSync(path.join(WORK, "results.json"), JSON.stringify({
    generatedAt: new Date().toISOString(), commit: spawnSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim(),
    runs: RUNS, bootSamples, results: results.map((r) => ({ ...r, route: { ...r.route, body: undefined },
      cold: r.cold && { ...r.cold, setCookie: undefined }, warm: r.warm.map((s) => ({ ...s, setCookie: undefined })) })), hot,
  }, null, 2));
  const md = renderReport(results, hot);
  console.log("\n" + md);
  if (WRITE_DOC) {
    const existing = fs.existsSync(DOC_PATH) ? fs.readFileSync(DOC_PATH, "utf8") : "# CPU profile (Workers Free, 10 ms per request)\n";
    fs.writeFileSync(DOC_PATH, replaceBlock(existing, BEGIN, END, md));
    log(`wrote ${path.relative(ROOT, DOC_PATH)}`);
  }
  log(`done. Throwaway work dir (state, builds, wrangler log): ${WORK}`);
}

function renderReport(results: RouteResult[], hot: Hot[]): string {
  const cpus = os.cpus();
  const header = [
    `Generated ${new Date().toISOString()} on ${os.platform()} ${os.arch()}, ${cpus[0]?.model ?? "cpu"} x${cpus.length}, Node ${process.version}.`,
    `${RUNS} warm requests per route, ${COLD ? "cold = first request on a freshly started workerd" : "single shared instance (no cold column)"}.`,
    "CPU = OS user+system CPU of the workerd process around each request (settled for waitUntil work). Budget: 10 ms.",
  ];
  const med = (tag: string) => {
    const v = bootSamples.filter((b) => b.tag === tag && Number.isFinite(b.ms)).map((b) => b.ms).sort((a, b) => a - b);
    return v.length ? `${fmt(v[Math.floor(v.length / 2)], 0)} ms (n=${v.length})` : "n/a";
  };
  header.push(
    `Boot CPU already spent when wrangler reports "Ready" (runtime start + Worker script evaluation, before any request): OpenNext Worker median ${med("wrangler.min.json")}, empty Worker ${med("wrangler.json")}.`,
  );
  const rows = results.map((r) => [
    r.route.name,
    r.status,
    r.cold ? fmt(r.cold.cpuMs) : "-",
    fmt(r.warmCpu.p50),
    fmt(r.warmCpu.p95),
    fmt(r.warmCpu.max),
    fmt(r.warmWall.p50),
    r.cacheLabel,
    `${r.warmCpu.p50 > 10 ? "OVER" : r.warmCpu.p95 > 10 ? "p95 over" : r.cold && r.cold.cpuMs > 10 ? "cold over" : "ok"}`,
  ]);
  const table = mdTable(
    ["Route", "HTTP", "Cold CPU ms", "Warm p50", "Warm p95", "Warm max", "Warm wall p50", "x-nextjs-cache (cold / warm)", "vs 10 ms"],
    rows,
  );
  const parts = [header.join("\n\n"), table];
  if (hot.length) {
    parts.push("### Hot functions (unminified build, V8 sampling profiler)");
    parts.push(
      "V8 samples at 100 us but fires on wall time, so each sample is weighted at most 400 us (self time ~ sample count). Profiling overhead inflates absolute ms: use it for RANKING; `%` is the share of non-idle samples and `ms/req` is that share applied to the profiled non-idle total.",
    );
    for (const h of hot) {
      parts.push(`#### ${h.route} (${h.busyMs.toFixed(1)} ms non-idle per request while profiled)`);
      parts.push(mdTable(["Function - module:line", "self ms/req", "%"], h.top.map((t) => [t.label, fmt(t.selfMs, 2), fmt(t.pct, 1)])));
      parts.push(mdTable(["Module / package", "self ms/req", "%"], h.byModule.map((t) => [t.label, fmt(t.selfMs, 2), fmt(t.pct, 1)])));
    }
  }
  return parts.join("\n\n");
}

main().catch((err) => {
  console.error("[perf:cpu] FAILED:", err instanceof Error ? err.stack : err);
  process.exitCode = 1;
}).finally(cleanup);
