type CdpNode = {
  id: number;
  callFrame: { functionName: string; scriptId: string; url: string; lineNumber: number; columnNumber: number };
};
type CdpProfile = { nodes: CdpNode[]; samples: number[]; timeDeltas: number[] };

class Cdp {
  private ws: WebSocket;
  private id = 0;
  private pending = new Map<number, { finish: (m: { result?: unknown; error?: { message: string } }) => void; reject: (err: Error) => void }>();
  scripts = new Map<string, string>(); // scriptId -> url

  private constructor(ws: WebSocket) {
    this.ws = ws;
    ws.onclose = () => {
      for (const pending of this.pending.values()) pending.reject(new Error("CDP connection closed"));
      this.pending.clear();
    };
    ws.onmessage = (ev: MessageEvent) => {
      const msg = JSON.parse(String(ev.data));
      if (msg.id && this.pending.has(msg.id)) {
        this.pending.get(msg.id)!.finish(msg);
        this.pending.delete(msg.id);
      } else if (msg.method === "Debugger.scriptParsed") {
        this.scripts.set(msg.params.scriptId, msg.params.url);
      }
    };
  }

  static async connect(inspectorPort: number): Promise<Cdp> {
    // wrangler's inspector proxy insists on an Origin header; Node's WebSocket (undici) accepts init.headers.
    const Ctor = WebSocket as unknown as new (url: string, init: { headers: Record<string, string> }) => WebSocket;
    const ws = new Ctor(`ws://127.0.0.1:${inspectorPort}/ws`, {
      headers: { Origin: "https://devtools.devprod.cloudflare.dev" },
    });
    await new Promise<void>((resolve, reject) => {
      const timer = setTimeout(() => { ws.close(); reject(new Error("CDP connection timed out")); }, 15_000);
      ws.onopen = () => { clearTimeout(timer); resolve(); };
      ws.onerror = () => { clearTimeout(timer); reject(new Error("CDP websocket failed to open")); };
    });
    return new Cdp(ws);
  }

  send<T = unknown>(method: string, params: Record<string, unknown> = {}): Promise<T> {
    return new Promise((resolve, reject) => {
      const id = ++this.id;
      const timer = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error(`CDP ${method} timed out`));
      }, 30_000);
      const fail = (err: Error) => { clearTimeout(timer); reject(err); };
      this.pending.set(id, { reject: fail, finish: (m) => {
        clearTimeout(timer);
        if (m.error) fail(new Error(`${method}: ${m.error.message}`));
        else resolve(m.result as T);
      } });
      this.ws.send(JSON.stringify({ id, method, params }));
    });
  }

  close() {
    this.ws.close();
  }
}

