// Record workerd PIDs at spawn time instead of scanning unrelated OS processes.
// This preload runs only in the profiler's Node children, never inside the Worker.
function writeChildTracker(): string {
  const file = path.join(WORK, "track-workerd.cjs");
  fs.writeFileSync(file, `const cp = require("node:child_process");
const fs = require("node:fs");
const spawn = cp.spawn;
cp.spawn = function(command, args, ...rest) {
  const child = spawn.call(this, command, args, ...rest);
  if (String(command).includes("workerd") && args?.some(a => String(a).startsWith("--inspector-addr"))) {
    child.once("spawn", () => fs.writeFileSync(process.env.DH_CPU_PID_FILE, String(child.pid)));
  }
  return child;
};
require("node:module").syncBuiltinESMExports();
`);
  return file;
}

async function startInstance(config: string, port: number, inspectorPort?: number): Promise<Instance> {
  inspectorPort ??= await freePort();
  const pidFile = path.join(WORK, `workerd-${port}.pid`);
  fs.rmSync(pidFile, { force: true });
  const tracker = writeChildTracker();
  const wranglerBin = path.join(ROOT, "node_modules", ".bin", "wrangler");
  const args = [
    "dev",
    "-c",
    config,
    "--persist-to",
    STATE_ROOT,
    "--port",
    String(port),
    "--ip",
    "127.0.0.1",
    "--show-interactive-dev-session=false",
    ...(inspectorPort ? ["--inspector-port", String(inspectorPort)] : []),
  ];
  const logFile = fs.createWriteStream(path.join(WORK, "wrangler-dev.log"), { flags: "a" });
  const proc = spawn(wranglerBin, args, {
    detached: true,
    cwd: WORK, // keeps wrangler's .wrangler/tmp out of the repo
    env: {
      ...process.env,
      WRANGLER_SEND_METRICS: "false",
      NO_COLOR: "1",
      DH_LOCAL_STATE_DIR: STATE_DIR,
      NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ""} --require ${JSON.stringify(tracker)}`,
      DH_CPU_PID_FILE: pidFile,
      // wrangler's local trace/log capture adds per-request CPU that production does not have.
      X_LOCAL_EXPLORER: "false",
      X_LOCAL_OBSERVABILITY: "false",
    },
    stdio: ["ignore", "pipe", "pipe"],
  });
  children.add(proc);
  let spawnError: Error | undefined;
  proc.on("error", (err) => { spawnError = err; });
  let ready = false;
  let output = "";
  const onData = (d: Buffer) => {
    const text = d.toString();
    logFile.write(text);
    output = (output + text).slice(-4000);
    if (output.includes("Ready on")) ready = true;
  };
  proc.stdout!.on("data", onData);
  proc.stderr!.on("data", onData);
  let exited = false;
  proc.on("exit", () => {
    exited = true;
  });
  try {
    const deadline = Date.now() + 120_000;
    while (!ready) {
      if (spawnError) throw spawnError;
      if (exited) throw new Error(`wrangler dev exited early; see ${path.join(WORK, "wrangler-dev.log")}`);
      if (Date.now() > deadline) throw new Error("wrangler dev did not become ready in 120 s");
      await sleep(100);
    }
    if (!fs.existsSync(pidFile)) throw new Error("No user-workerd PID was recorded");
    const workerdPid = Number(fs.readFileSync(pidFile, "utf8"));
    if (!Number.isSafeInteger(workerdPid) || workerdPid < 1) throw new Error("Invalid workerd PID");
    await sleep(150); // let the runtime finish evaluating the script
    const bootCpuMs = meterRef ? (await meterRef.read(workerdPid)) / 1e6 : NaN;
    bootSamples.push({ tag: path.basename(config), ms: bootCpuMs });
    return {
      proc,
      workerdPid,
      bootCpuMs,
      port,
      stop: async () => {
        await stopChild(proc);
        logFile.end();
      },
    };
  } catch (err) {
    await stopChild(proc);
    logFile.end();
    throw err;
  }
}

