// ============================================================================
// LOCAL WORKER CPU PROFILER (`npm run perf:cpu`)
// ----------------------------------------------------------------------------
// Question it answers: which routes would blow the Workers FREE plan's 10 ms
// CPU-per-request budget? It builds the real OpenNext Worker, runs it under
// workerd (`wrangler dev` on the .open-next output) against a THROWAWAY local
// D1/R2 state dir seeded with realistic content, requests every route type
// cold (fresh workerd, first request) and warm, and records CPU per request.
//
// HOW CPU IS MEASURED (and why)
//   * workerd's tail events carry `cpuTime`/`wallTime` but the open-source
//     workerd reports 0 for both (verified: tail-worker and wrangler's local
//     observability both show cpu_time_ms: 0), so they are unusable locally.
//   * The V8 sampling profiler (CDP Profiler over `wrangler dev`'s inspector)
//     samples WALL time and only marks "(idle)" some of the time, so summing
//     its samples overstates CPU. It is used only to RANK hot functions.
//   * What we use for the numbers: the OS CPU counter (user+system, ns) of
//     the workerd process that runs the Worker, read immediately before and
//     after each request (plus a short settle so waitUntil() work is
//     included). workerd is single-threaded for request work, so the delta
//     is the CPU the request cost, including GC, background threads and local D1/R2 emulation.
//   * CAVEATS: local CPU is NOT Cloudflare edge CPU (different CPU, no V8
//     snapshot/code cache, local D1 and R2 emulation burns CPU that is I/O
//     wait on the real platform, so DB-heavy routes read high). Treat the
//     table as relative ranking, not an edge measurement or a strict upper bound.
//
// Needs: macOS (python3 + libproc for ns-resolution CPU) or Linux (/proc,
// 10 ms ticks: use more --runs). Local only; never touches Cloudflare.
//
// Usage: npm run perf:cpu -- [--runs 30] [--no-cold] [--no-hot] [--skip-build]
//        [--work-dir DIR] [--routes "/,/about"] [--no-doc] [--hot-top 3]
// ============================================================================

