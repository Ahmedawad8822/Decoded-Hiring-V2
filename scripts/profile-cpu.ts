type Sample = { cpuMs: number; wallMs: number; status: number; cache: string; bytes: number; setCookie: string | null };

let xffCounter = 0;
const runSalt = 17; // fresh state + fixed request order make rate-limit buckets repeatable

async function measureOnce(
  inst: Instance,
  meter: CpuMeter,
  route: CpuRoute,
  cookies: Record<string, string>,
  profiling = false,
): Promise<Sample> {
  const url = `http://127.0.0.1:${inst.port}${route.path}`;
  const headers: Record<string, string> = { accept: "text/html,application/xhtml+xml" };
  const cookie = cookies[route.auth];
  if (cookie) headers.cookie = cookie;
  if (route.method === "POST") {
    headers["content-type"] = "application/json";
    headers.origin = `http://127.0.0.1:${inst.port}`;
    // Auth rate limits are per client IP; the app trusts x-forwarded-for locally.
    xffCounter += 1;
    const ip = `10.${100 + (runSalt % 100)}.${(xffCounter >> 8) & 255}.${xffCounter & 255}`;
    headers["x-forwarded-for"] = ip;
    headers["cf-connecting-ip"] = ip; // wrangler dev would otherwise stamp 127.0.0.1 on every request
  }
  const c0 = await meter.read(inst.workerdPid);
  const t0 = performance.now();
  const res = await fetch(url, {
    method: route.method ?? "GET",
    headers,
    body: route.body ? JSON.stringify(route.body) : undefined,
    redirect: "manual",
    signal: AbortSignal.timeout(60_000),
  });
  const body = await res.arrayBuffer();
  const wallMs = performance.now() - t0;
  // Include immediate waitUntil/cache writes. With the profiler enabled, sampling
  // itself burns CPU while idle: use a bounded 16 ms settle, never the strict gate.
  let prev = await meter.read(inst.workerdPid);
  let stable = 0;
  for (let i = 0; i < (profiling ? 2 : 60) && stable < 2; i++) {
    await sleep(8);
    const cur = await meter.read(inst.workerdPid);
    stable = cur - prev < 20_000 ? stable + 1 : 0; // < 20 us of new CPU
    prev = cur;
  }
  if (res.status !== 200) throw new Error(`${route.name}: expected HTTP 200, got ${res.status}`);
  if (!profiling && stable < 2) throw new Error(`${route.name}: workerd CPU did not settle after the request`);
  return {
    cpuMs: (prev - c0) / 1e6,
    wallMs,
    status: res.status,
    cache: res.headers.get("x-nextjs-cache") ?? "",
    bytes: body.byteLength,
    setCookie: res.headers.get("set-cookie"),
  };
}

function sessionCookie(setCookie: string | null): string | null {
  if (!setCookie) return null;
  const m = setCookie.match(/better-auth\.session_token=[^;]+/);
  return m ? m[0] : null;
}

