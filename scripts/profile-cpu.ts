function statusLabel(cold: Sample | undefined, warm: Sample[]): string {
  const counts = new Map<number, number>();
  for (const x of [...(cold ? [cold] : []), ...warm]) counts.set(x.status, (counts.get(x.status) ?? 0) + 1);
  return counts.size === 1 ? String([...counts.keys()][0]) : [...counts.entries()].map(([k, v]) => `${k}x${v}`).join(" ");
}

function cacheLabel(cold: Sample | undefined, warm: Sample[]): string {
  const norm = (c: string) => c || "-";
  const counts = new Map<string, number>();
  for (const s of warm) counts.set(norm(s.cache), (counts.get(norm(s.cache)) ?? 0) + 1);
  const warmPart = [...counts.entries()].map(([k, v]) => `${k} ${v}/${warm.length}`).join(", ");
  return `${cold ? norm(cold.cache) : "n/a"} / ${warmPart}`;
}

